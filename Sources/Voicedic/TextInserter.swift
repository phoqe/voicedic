import AppKit
import ApplicationServices

/// Inserts text into the focused app by putting it on the pasteboard and sending ⌘V,
/// then restoring whatever was on the pasteboard before.
@MainActor
enum TextInserter {
    enum Outcome {
        case pasted
        /// No Accessibility access, so the text was left on the clipboard instead.
        case copiedOnly
    }

    static func insert(_ text: String) async -> Outcome {
        let pasteboard = NSPasteboard.general

        guard AXIsProcessTrusted() else {
            pasteboard.clearContents()
            pasteboard.setString(text, forType: .string)
            return .copiedOnly
        }

        let saved = snapshot(pasteboard)

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Ask clipboard managers not to record this (nspasteboard.org convention).
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        sendCommandV()

        // Give the target app time to read the pasteboard before restoring it.
        try? await Task.sleep(for: .milliseconds(400))
        if pasteboard.changeCount == ourChange, !saved.isEmpty {
            pasteboard.clearContents()
            pasteboard.writeObjects(saved)
        }
        return .pasted
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) {
                    copy.setData(data, forType: type)
                }
            }
            return copy
        }
    }

    private static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9  // kVK_ANSI_V
        let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
